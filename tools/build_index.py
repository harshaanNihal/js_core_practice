#!/usr/bin/env python3
"""Regenerate the root index.html: one link per HTML page in the repo, grouped by top-level folder.

Run from anywhere:
    python3 tools/build_index.py --title "..." --blurb "..." --repo https://github.com/<user>/<repo> [--runnable PREFIX ...]

Pages that sit under a package.json need a build step and cannot run as plain static files,
so they are listed with a link to their source instead of a live link. Pass --runnable PREFIX
for a project that has a package.json but also works served as-is.
"""
import argparse
import html
import os
import re
import sys
from pathlib import Path
from urllib.parse import quote

MARKER = "<!-- generated by tools/build_index.py -->"
SKIP_DIRS = {".git", ".github", "node_modules", "dist", ".cache", ".parcel-cache", "tools"}


def natural_key(text):
    return [int(part) if part.isdigit() else part.lower() for part in re.split(r"(\d+)", text)]


def under_package_json(root, directory):
    current = directory
    while True:
        if (current / "package.json").exists():
            return True
        if current == root:
            return False
        current = current.parent


def collect(root, runnable_prefixes):
    """Return {group: [(label, rel_path, runnable)]} for every non-empty HTML file."""
    groups = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        directory = Path(dirpath)
        for name in filenames:
            path = directory / name
            if path.suffix.lower() != ".html" or path.stat().st_size == 0:
                continue
            rel = path.relative_to(root)
            if len(rel.parts) == 1:
                continue
            group, rest = rel.parts[0], list(rel.parts[1:])
            rest[-1] = rest[-1][: -len(path.suffix)]
            if rest[-1].lower() == "index" and len(rest) > 1:
                rest.pop()
            label = " / ".join(rest) if rest != ["index"] else "Open page"
            forced = any(rel.as_posix().startswith(prefix) for prefix in runnable_prefixes)
            groups.setdefault(group, []).append(
                (label, rel.as_posix(), forced or not under_package_json(root, directory))
            )
    for entries in groups.values():
        entries.sort(key=lambda e: natural_key(e[0]))
    return dict(sorted(groups.items(), key=lambda g: natural_key(g[0])))


def render(title, blurb, repo, groups):
    sections = []
    for group, entries in groups.items():
        items = []
        for label, rel, runnable in entries:
            if runnable:
                items.append(f'<li><a href="{quote(rel)}">{html.escape(label)}</a></li>')
            else:
                source = f"{repo}/tree/master/{quote(os.path.dirname(rel))}"
                items.append(
                    f'<li class="build"><a href="{source}">{html.escape(label)}</a>'
                    f" <span>needs a build, source only</span></li>"
                )
        sections.append(
            f"<section><h2>{html.escape(group)}</h2><ul>{''.join(items)}</ul></section>"
        )
    return f"""<!DOCTYPE html>
{MARKER}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>{html.escape(title)}</title>
<style>
:root {{ --bg: #fafafa; --fg: #1f2933; --muted: #616e7c; --card: #fff; --line: #d9e2ec; --accent: #0b6bcb; }}
@media (prefers-color-scheme: dark) {{
  :root {{ --bg: #12161c; --fg: #e4e7eb; --muted: #9aa5b1; --card: #1b222b; --line: #2f3a46; --accent: #6cb4ff; }}
}}
* {{ box-sizing: border-box; }}
body {{ margin: 0; padding: 0 16px 64px; background: var(--bg); color: var(--fg); font: 16px/1.5 system-ui, sans-serif; }}
main {{ max-width: 960px; margin: 0 auto; }}
h1 {{ margin: 48px 0 8px; font-size: 2rem; }}
.blurb {{ margin: 0 0 32px; color: var(--muted); }}
.blurb a {{ color: var(--accent); }}
section {{ margin: 0 0 24px; padding: 16px 20px; background: var(--card); border: 1px solid var(--line); border-radius: 8px; }}
h2 {{ margin: 0 0 8px; font-size: 1.1rem; }}
ul {{ margin: 0; padding: 0; list-style: none; columns: 2 260px; column-gap: 24px; }}
li {{ padding: 4px 0; break-inside: avoid; overflow-wrap: anywhere; }}
a {{ color: var(--accent); }}
li span {{ color: var(--muted); font-size: 0.85rem; }}
</style>
</head>
<body>
<main>
<h1>{html.escape(title)}</h1>
<p class="blurb">{html.escape(blurb)} Source on <a href="{repo}">GitHub</a>.</p>
{''.join(sections)}
</main>
</body>
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--title", required=True)
    parser.add_argument("--blurb", required=True)
    parser.add_argument("--repo", required=True, help="GitHub URL of this repo, no trailing slash")
    parser.add_argument("--runnable", action="append", default=[], metavar="PREFIX",
                        help="treat pages under this repo-relative path as runnable even below a package.json")
    args = parser.parse_args()

    root = Path(__file__).resolve().parent.parent
    target = root / "index.html"
    if target.exists() and MARKER not in target.read_text(encoding="utf-8", errors="replace"):
        sys.exit(f"{target} exists and was not generated by this script; refusing to overwrite it")

    groups = collect(root, args.runnable)
    target.write_text(render(args.title, args.blurb, args.repo.rstrip("/"), groups), encoding="utf-8")
    total = sum(len(entries) for entries in groups.values())
    print(f"wrote {target} with {total} pages in {len(groups)} groups")


if __name__ == "__main__":
    main()
